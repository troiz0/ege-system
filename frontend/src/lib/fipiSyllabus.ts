export type TopicMasteryStatus = 'not_started' | 'in_progress' | 'mastered';

export interface TopicProgress {
  topic: SyllabusTopic;
  status: TopicMasteryStatus;
  masteryPercent: number; // 0 - 100
  matchedWeakTopic?: WeakTopic;
}

/**
 * Оценивает статус освоения темы по списку WeakTopic пользователя
 */
export function getTopicProgress(topic: SyllabusTopic, weakTopics: WeakTopic[]): TopicProgress {
  if (!weakTopics || weakTopics.length === 0) {
    return { topic, status: 'not_started', masteryPercent: 0 };
  }

  const topicTitleLower = topic.title.toLowerCase();
  const keywords = topic.keywords || [];

  // Ищем совпадение в weakTopics
  const match = weakTopics.find((wt) => {
    const wtName = wt.topicName.toLowerCase();
    if (wtName.includes(topicTitleLower) || topicTitleLower.includes(wtName)) return true;
    return keywords.some((kw) => wtName.includes(kw.toLowerCase()));
  });

  if (!match) {
    return { topic, status: 'not_started', masteryPercent: 0 };
  }

  const level = typeof match.masteryLevel === 'number' ? match.masteryLevel : 0;
  const masteryPercent = Math.min(100, Math.max(0, Math.round(level * 100)));

  let status: TopicMasteryStatus = 'not_started';
  if (masteryPercent >= 80) {
    status = 'mastered';
  } else if (masteryPercent > 0) {
    status = 'in_progress';
  }

  return { topic, status, masteryPercent, matchedWeakTopic: match };
}

/**
 * Подсчитывает сводную статистику по предмету
 */
export function calculateSyllabusStats(syllabus: SubjectSyllabus, weakTopics: WeakTopic[]) {
  let totalTopics = 0;
  let mastered = 0;
  let inProgress = 0;
  let notStarted = 0;
  let totalMasterySum = 0;

  for (const sec of syllabus.sections) {
    for (const t of sec.topics) {
      totalTopics++;
      const prog = getTopicProgress(t, weakTopics);
      totalMasterySum += prog.masteryPercent;
      if (prog.status === 'mastered') mastered++;
      else if (prog.status === 'in_progress') inProgress++;
      else notStarted++;
    }
  }

  const overallPercent = totalTopics > 0 ? Math.round(totalMasterySum / totalTopics) : 0;

  return {
    totalTopics,
    mastered,
    inProgress,
    notStarted,
    overallPercent,
  };
}
