/**
 * Генерация уникального случайного варианта КИМ ЕГЭ-2027
 */
export function generateRandomExamVariant(subject = 'math_profile'): ExamVariant {
  // Генерируем 6-значный красивый код варианта (например, 482-915)
  const partA = Math.floor(100 + Math.random() * 900);
  const partB = Math.floor(100 + Math.random() * 900);
  const variantCode = `${partA}-${partB}`;
  const variantNumber = partA * 1000 + partB;

  const tasks: ExamTask[] = [];

  for (let num = 1; num <= 20; num++) {
    const pool = MATH_PROFILE_TASK_POOLS[num];
    if (!pool || pool.length === 0) continue;

    // Случайный выбор задачи из пула
    const randomIndex = Math.floor(Math.random() * pool.length);
    const template = pool[randomIndex];

    const isPart1 = num <= 13;
    tasks.push({
      taskNumber: num,
      fipiId: `FIPI-${variantNumber}-${num}`,
      topic: template.topic,
      statement: template.text,
      correctAnswer: template.correctAnswer,
      solutionCriteria: template.fipiCriteria,
      maxScore: template.maxScore,
      type: isPart1 ? 'SHORT' : 'DETAILED',

      // Legacy
      id: num,
      part: isPart1 ? 1 : 2,
      number: num,
      title: template.title,
      text: template.text,
      fipiCriteria: template.fipiCriteria,
    });
  }

  return {
    id: `math_profile_var_${variantNumber}`,
    subject,
    subjectName: 'Математика (профиль)',
    variantNumber,
    variantCode,
    title: `Официальный вариант ФИПИ ЕГЭ-2027 № ${variantCode}`,
    timeLimitSeconds: 14100, // 3 часа 55 минут
    totalTasks: 20,
    part1Count: 13,
    part2Count: 7,
    maxPrimaryScore: 33,
    tasks,
  };
}

export function getExamVariant(subject = 'math_profile', _variantNumber = 1): ExamVariant {
  return generateRandomExamVariant(subject);
}
