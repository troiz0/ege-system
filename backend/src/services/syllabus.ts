export const FALLBACK_TOPICS = [
  'Задания части 1: Базовая техника КИМ',
  'Задания части 2: Развернутые решения и критерии ФИПИ',
  'КИМ 2027: Полный срез пробного экзамена',
];

export function topicsFor(subject: string, targetScore?: number): string[] {
  const k = subject.trim().toLowerCase();
  const allTopics = SYLLABUS[ALIASES[k] ?? k] ?? FALLBACK_TOPICS;

  if (!targetScore) return allTopics;

  // Адаптация тем под целевой балл ученика
  if (targetScore < 70) {
    // Фокус на части 1 (первые 50% тем спецификации)
    return allTopics.slice(0, Math.max(3, Math.ceil(allTopics.length * 0.5)));
  } else if (targetScore < 85) {
    // Часть 1 + джентльменский набор части 2 (до 80% тем)
    return allTopics.slice(0, Math.max(4, Math.ceil(allTopics.length * 0.8)));
  }

  // 85–100 баллов: полный объем спецификации, включая олимпиадный блок и сложные задачи
  return allTopics;
}
